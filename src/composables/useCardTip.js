/**
 * 身份证后 6 位输入框的「失焦即提示」—— 参演人员表 / 指导教师表 **共用的一份实现**
 *
 * ===========================================================================
 * 【为什么要有这个文件】
 * ===========================================================================
 * 原先「身份证后6位」填错，只有点「暂存 / 提交」时才会由各表的 checkLine() 报出来，
 * 走的是一条 ElMessage.error（`参演人员名单第N行身份证后6位应为6位…`）。
 * 问题不在于报得晚，而在于**报得远**：一张 60 行的表里弹出这么一句，用户得自己
 * 回表里数第 N 行、再肉眼比对是哪一位不对 —— 提示与出错的格子不在同一处视线里。
 *
 * 改成「移开输入框就在该格下方出一行红字」后，提示与出错的值贴在一起，
 * 用户不用数行号、也不用记忆提示内容。
 *
 * ===========================================================================
 * 【判据一份，不新增第二套规则】
 * ===========================================================================
 * 这里**只负责"什么时候显示"**，"什么算错"一律调用
 * @/config/personFields 的 checkPersonCard —— 它与后端 models.normalize_card
 * 逐字同源（正则与文案都是抄过来的）。本文件里不得出现第二份正则或第二份文案，
 * 否则日后再改口径就会漏掉这一处（personFields.js 的文件头已经把这条写过一次）。
 *
 * 【为什么空值不提示】空是「必填」的事，由各表的 checkLine 在提交时统一报
 * （文案是「身份证后6位不能为空」）。checkPersonCard 对空值返回 null，
 * 这里因此也天然不提示 —— 用户点进空格子再移开，不该平白弹一条格式错误。
 *
 * 【显示时机：失焦判、输入即清】
 *   · blur  —— 重新判一次，不合格就把文案挂到那一行上；
 *   · input —— 只要用户开始改动就立刻撤掉红字（不判、不挂新的）。
 * 两者合起来的效果是「红字只描述用户已经填完并离开的那个值」。
 * 若输入也判，用户刚敲第一个字符就会满屏红字，那是噪声不是提示。
 *
 * ===========================================================================
 * 【为什么用 Map 挂在 item 对象上，而不是数组下标或往 item 里塞字段】
 * ===========================================================================
 *   · 不用下标：TeacherTable 里有一行「教师指挥带入行」，它插在 data 之外，
 *     屏幕上的行号（rowNo）与 data 下标并不相等；下标做键，插一行就整体错位。
 *   · 不往 item 里塞字段（如 item.cardError）：item 就是提交数据的载体，
 *     getCacheData() 会把它原样交出去。当前 config/draftPayload.js 的
 *     personToPayload 是精确白名单（多一个键确实不会被发出去），但把 UI 状态
 *     混进数据对象，等于给下一条"顺手 ...spread"的代码埋雷。
 *   · Map 以 item 对象的**引用**为键，天然跟着行走：删行、重排、换内容都不会错位 ——
 *     删掉第 3 行后，原来的第 4 行仍然带着自己的红字（若按下标存，红字会整体串位，
 *     第 4 行凭空显示第 3 行的错误）。
 *
 * 【什么时候需要手动清】条目只会被「整份名单被换掉」的三个时点弄脏：清空表格、
 * Excel 导入重建、父组件换了一份 showdata（编辑页回填 / 切换报表）。这三处调
 * clearCardTips()。单个删行**不必**清：被删的那一行已经不在 data 里，它的条目
 * 没有任何消费者，而下一次整批替换会把残留一起清掉 —— 也正因为如此，清的时候
 * 只能整份清（clearCardTips），不能按行清，否则会把其它行还没处理的红字一起抹掉。
 *
 * 【为什么是 reactive(new Map())】Vue 3 的响应式集合：get/set/delete 都按**键**收集
 * 与触发依赖，模板里 `cardTip(item)` 因此能在那一行被写入或撤销时精确重渲染。
 * 用 toRaw 包一层或普通 Map 都不会触发视图更新。
 *
 * 【一个实例一份状态】写成 composable 而非常量，是因为两张表各自有独立的 data 与
 * 生命周期；共用一个模块级 Map 会让两个组件互相看到对方的提示。
 */
import { reactive } from 'vue'
import { checkPersonCard } from '@/config/personFields'

export function useCardTip() {
  /** item 对象 → 该行当前要显示的红字（没有条目 = 不显示） */
  const tips = reactive(new Map())

  /** 模板里取用：`v-if="cardTip(item)"` */
  function cardTip(item) {
    return tips.get(item) || ''
  }

  /** el-input 的 @blur：这一刻的值定去留 */
  function onCardBlur(item) {
    if (!item) return
    const msg = checkPersonCard(item.card)
    if (msg) tips.set(item, msg)
    else tips.delete(item)
  }

  /** el-input 的 @input：用户一动就撤红字，等他离开这一格再判 */
  function onCardInput(item) {
    if (!item) return
    tips.delete(item)
  }

  /** 清空表格 / 整批换数据时调用，免得已经不在表里的行还占着条目 */
  function clearCardTips() {
    tips.clear()
  }

  return { cardTip, onCardBlur, onCardInput, clearCardTips }
}
