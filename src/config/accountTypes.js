/**
 * 账号类型（user.type）-> 中文名 —— 全站唯一来源
 *
 * 【为什么单开一个文件】
 * 原先这份字典只写在 views/admin/user.vue 里。组委会端 /committee/user 要显示
 * 同一列「类型」时，就得再抄一份 —— 两份副本的坏处不是"看着重复"，而是将来
 * 类型有增减（例如省级 type=4 重新上线）时漏改一处，那一页的类型列会渲染成空白。
 * 界面上看不出是漏改，只会被当成"这个账号没类型"，很难往字典上想。
 *
 * 【取值依据】后端 apps/core/models.py:76-82 的常量定义，
 * 以及同目录 migrations/0010_update_type_comments.py 里同步的数据库列注释：
 *   0=学校 1=市州（只读，报名功能已移出） 2=组委会 3=管理员 4=省级 5=中小学端
 *
 * 【为什么 2/3/4 也写进来，明明列表接口看不到它们】
 * 列表接口（admin 与 committee 走同一个 user_list）的过滤条件是
 * type__in=(0, 1, 5)，所以这一列本该只出现 0/1/5。
 * 但两页的模板都写了 `TYPE_LABEL[row.type] ?? row.type` 做兜底 ——
 * 万一后端以后放开过滤、遇到表里没有的值，有中文名总比显示裸数字强；
 * 而且这三行是"照抄数据库注释"，少写反而会让后来的人以为是漏了。
 *
 * 【本文件的性质】**只读的展示字典** —— 只做"数字转人话"，
 * 不参与任何权限判断、不决定谁能看见谁。改动它不会影响任何逻辑。
 *
 * 【为什么不放进 config/roles.js】
 * 那里只有数字常量 ROLE.SCHOOL / CITY / …，没有中文名，而且**故意没有 4**
 * （省级已下线）—— 硬引过来会漏掉 4 这一档。这里要的是"把可能出现的值都显示成
 * 人话"，与 roles.js「谁有权限」的目标不同，所以分开两个文件。
 */
